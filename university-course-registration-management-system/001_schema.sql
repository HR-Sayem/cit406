-- University Course Registration and Department Management System
-- Based on the corrected CIT 406 project proposal (eight entities).
-- Run this file first in a Supabase PostgreSQL SQL Editor, then run seed.sql.
-- All project tables live in university_registration to avoid changing other
-- tables in the Supabase public schema. Re-running this file retains data.
-- For a CLEAN rebuild only, manually run:
--   DROP SCHEMA IF EXISTS university_registration CASCADE;
-- Then run schema.sql followed by seed.sql. DROP SCHEMA deletes project data.
-- The application must ensure that enrollment counts stay within section
-- maximum_capacity and that classroom time slots do not overlap; these
-- cross-row scheduling rules are not enforced by the simple ERD schema.

BEGIN;
CREATE SCHEMA IF NOT EXISTS university_registration;

CREATE TABLE IF NOT EXISTS university_registration.department (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    office_location VARCHAR(100),
    phone_number VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS university_registration.student (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    date_of_birth DATE,
    department_id INTEGER NOT NULL,
    -- RESTRICT: a department with students must be retained or its students
    -- reassigned; deleting it must not erase students or orphan their major.
    -- UPDATE CASCADE: a corrected department ID follows its student records.
    CONSTRAINT student_department_fk FOREIGN KEY (department_id)
        REFERENCES university_registration.department(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS university_registration.instructor (
    instructor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    department_id INTEGER NOT NULL,
    -- RESTRICT: retain departments employing instructors until reassignment.
    -- UPDATE CASCADE: a corrected department ID updates the affiliation.
    CONSTRAINT instructor_department_fk FOREIGN KEY (department_id)
        REFERENCES university_registration.department(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS university_registration.course (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL UNIQUE,
    course_name VARCHAR(150) NOT NULL,
    credit_hours INTEGER NOT NULL CHECK (credit_hours BETWEEN 1 AND 6),
    description TEXT,
    department_id INTEGER NOT NULL,
    -- RESTRICT: keep a department while it owns catalog courses.
    -- UPDATE CASCADE: a corrected department ID follows its courses.
    CONSTRAINT course_department_fk FOREIGN KEY (department_id)
        REFERENCES university_registration.department(department_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS university_registration.semester (
    semester_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_name VARCHAR(40) NOT NULL,
    academic_year INTEGER NOT NULL CHECK (academic_year BETWEEN 2000 AND 2200),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT semester_dates_valid CHECK (end_date >= start_date),
    CONSTRAINT semester_name_year_unique UNIQUE (semester_name, academic_year)
);

CREATE TABLE IF NOT EXISTS university_registration.classroom (
    classroom_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_name VARCHAR(100) NOT NULL,
    room_number VARCHAR(20) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    CONSTRAINT classroom_location_unique UNIQUE (building_name, room_number)
);

CREATE TABLE IF NOT EXISTS university_registration.section (
    section_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_number VARCHAR(20) NOT NULL,
    schedule VARCHAR(120) NOT NULL,
    maximum_capacity INTEGER NOT NULL CHECK (maximum_capacity > 0),
    course_id INTEGER NOT NULL,
    instructor_id INTEGER NOT NULL,
    semester_id INTEGER NOT NULL,
    classroom_id INTEGER NOT NULL,
    CONSTRAINT section_offering_unique UNIQUE (course_id, semester_id, section_number),
    -- RESTRICT: a course with offered sections remains in the catalog.
    -- UPDATE CASCADE: corrected course IDs propagate to offerings.
    CONSTRAINT section_course_fk FOREIGN KEY (course_id)
        REFERENCES university_registration.course(course_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- RESTRICT: reassign sections before deleting their instructor.
    -- UPDATE CASCADE: corrected instructor IDs propagate to sections.
    CONSTRAINT section_instructor_fk FOREIGN KEY (instructor_id)
        REFERENCES university_registration.instructor(instructor_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- RESTRICT: a semester with sections remains available for history.
    -- UPDATE CASCADE: corrected semester IDs propagate to sections.
    CONSTRAINT section_semester_fk FOREIGN KEY (semester_id)
        REFERENCES university_registration.semester(semester_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- RESTRICT: relocate sections before deleting an assigned classroom.
    -- UPDATE CASCADE: corrected classroom IDs propagate to sections.
    CONSTRAINT section_classroom_fk FOREIGN KEY (classroom_id)
        REFERENCES university_registration.classroom(classroom_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS university_registration.enrollment (
    enrollment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    section_id INTEGER NOT NULL,
    enrollment_date DATE NOT NULL,
    enrollment_status VARCHAR(20) NOT NULL
        CHECK (enrollment_status IN ('Enrolled', 'Completed', 'Dropped')),
    grade VARCHAR(3),
    CONSTRAINT enrollment_student_section_unique UNIQUE (student_id, section_id),
    CONSTRAINT enrollment_grade_valid CHECK
        (grade IS NULL OR grade IN ('A', 'A-', 'B+', 'B', 'B-', 'C+', 'C', 'C-', 'D', 'F', 'W')),
    -- RESTRICT: preserve a student's registration and grade history;
    -- remove or archive enrollment records explicitly before deletion.
    -- UPDATE CASCADE: corrected student IDs keep enrollment links valid.
    CONSTRAINT enrollment_student_fk FOREIGN KEY (student_id)
        REFERENCES university_registration.student(student_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- RESTRICT: do not erase enrollment/grades by deleting a section.
    -- UPDATE CASCADE: corrected section IDs keep enrollment links valid.
    CONSTRAINT enrollment_section_fk FOREIGN KEY (section_id)
        REFERENCES university_registration.section(section_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMIT;
